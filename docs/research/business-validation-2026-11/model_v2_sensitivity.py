# ---- 11. Monte Carlo ----
print("## 11. Monte Carlo: how often does ₹799 clear thresholds? (triangular draws, conservative to optimistic, mode = base)\n")
random.seed(7)
keys = ["pay", "mixdisc", "wait_min", "idle", "pg", "fp", "collect", "fc", "prem", "churn", "cac", "vpf"]


def draw():
    P = dict(BASE)
    for k in keys:
        lo, hi = sorted((CON[k], OPT[k]))
        if lo == hi:
            continue
        P[k] = random.triangular(lo, hi, min(max(BASE[k], lo), hi))
    return P


N = 20000
res = {15: [], 40: [], 75: []}
for _ in range(N):
    P = draw()
    for f in res:
        res[f].append(unit(f, P)["cm"])
rows = []
for f, a in res.items():
    a = np.array(a)
    rows.append((f, r(np.percentile(a, 10)), r(np.percentile(a, 50)), r(np.percentile(a, 90)),
                 f"{(a > 150).mean() * 100:.0f}%", f"{(a > 250).mean() * 100:.0f}%"))
tbl(["Families", "P10 CM ₹", "Median ₹", "P90 ₹", "P(CM > ₹150, kill line)", "P(CM > ₹250)"], rows)
print("Triangular ranges are my judgement, not data. Treat percentages as a stress test, not forecasts.\n")
