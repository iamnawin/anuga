"""AnugaCare model v2: sensitivity / validation layer on top of the v1 model (v1-original/).

Run:  python3 model_v2_sensitivity.py > model_v2_results.md
Nothing here is verified market data. Every input is an [E] estimate unless a comment says otherwise.
v1 files are preserved unchanged in v1-original/. This file does not import or edit them.
"""
import random
import numpy as np

# ---------- v1 curves (copied verbatim from model2.py so results are comparable) ----------
FX = [(0, 60000), (15, 82000), (75, 299000), (400, 1100000)]


def fixed_curve(f):
    return float(np.interp(f, [a for a, _ in FX], [b for _, b in FX]))


def batch(f, k):
    return k * float(np.interp(f, [0, 15, 75, 400], [0.10, 0.15, 0.35, 0.55]))


# ---------- parameter sets ----------
FARE = 400  # avg prepaid round-trip fare, pass-through (v1 value)
# Package mix of visits: 12-trip (60%), 8-trip (20%), 4-trip + single (20%). Discount factors vs 799 list.
MIX_DISC = 0.6 * (8499 / 12 / 799) + 0.2 * (5899 / 8 / 799) + 0.2 * 1.0

V1 = dict(  # replicates model2.py 'base' exactly
    name="v1_replica", list=750, mixdisc=1.0, gst="none",
    pay=300, bratio=230 / 300, bf=1.0, wait_min=0, wait_rate=100, idle=0.10,
    pg=0.02, sup=30, ins=15, comm=8, train=12,
    flat_leak=0.05, fp=0, collect=1, showup=0, fc=0, prem=1, credit=0, sup_f=0, sup_c=0,
    resched=0, rcost=0, churn=0, cac=0, vpf=10)

BASE = dict(  # v2 realistic base
    name="v2_base", list=799, mixdisc=MIX_DISC, gst="none",
    pay=380,          # v1 300 + ~80 companion own commute (bike/auto/bus, 2 solo legs). [E]
    bratio=0.77,      # batched trip pay ratio (v1: 230/300)
    bf=1.0, wait_min=20, wait_rate=100, idle=0.08,
    pg=0.0236,        # Razorpay standard 2% + 18% GST on fee [V: razorpay.com]; direct UPI would be ~0
    sup=30, ins=15, comm=8, train=12, flat_leak=None,
    fp=0.05, collect=0.70, showup=150,   # patient late-cancel/no-show: 5% of slots, 70% of fee collected
    fc=0.03, prem=1.15, credit=150, sup_f=30, sup_c=60,  # company failure 3%: free trip + 150 credit + replacement
    resched=0.04, rcost=20, churn=0.06, cac=3000, vpf=10)

OPT = dict(BASE, name="v2_optimistic", mixdisc=0.95, pay=330, wait_min=10, idle=0.05, pg=0.01,
           fp=0.03, collect=0.80, fc=0.02, churn=0.04, cac=2000, vpf=11)
CON = dict(BASE, name="v2_conservative", mixdisc=0.89, pay=430, wait_min=30, idle=0.12,
           fp=0.07, collect=0.60, fc=0.05, prem=1.30, churn=0.08, cac=5000, vpf=8)


def unit(f, P):
    real = P["list"] * P["mixdisc"]
    net = real / 1.18 if P["gst"] == "absorb" else real  # absorb = price is tax-inclusive, 18% GST applies
    b = min(batch(f, P["bf"]), 0.75)
    pay = P["pay"] * (1 - b) + P["pay"] * P["bratio"] * b
    wait = P["wait_min"] / 60 * P["wait_rate"]
    idle = P["idle"] * pay
    other = P["sup"] + P["ins"] + P["comm"] + P["train"]
    base_visit_cost = pay + wait + idle + other
    n_c = 100 * (1 - P["fp"] - P["fc"])  # completed visits per 100 booked slots
    rev = n_c * net + 100 * P["fp"] * P["collect"] * net
    fail_cost = (100 * P["fp"] * (P["showup"] + P["sup_f"])
                 + 100 * P["fc"] * (pay * P["prem"] + P["credit"] + P["sup_c"])
                 + 100 * P["resched"] * P["rcost"])
    pgfee = P["pg"] * (rev + n_c * FARE)
    cost = n_c * base_visit_cost + fail_cost + pgfee
    if P["flat_leak"] is not None:
        cost += n_c * P["flat_leak"] * net
    acq = P["churn"] * P["cac"] / P["vpf"]  # replacement acquisition cost per visit
    cm_pre_acq = (rev - cost) / n_c
    return dict(real=real, net=net, pay=pay, wait=wait, idle=idle, other=other,
                fail_cost=fail_cost / n_c, pgfee=pgfee / n_c, acq=acq,
                late_fee_rev=(rev - n_c * net) / n_c, cm_pre_acq=cm_pre_acq, cm=cm_pre_acq - acq,
                rev_per_completed=rev / n_c, batch=b)


def be_visits(F, cm):
    return F / cm if cm > 0 else float("inf")


def selfconsistent_be(P):
    for f in range(1, 801):
        if f * P["vpf"] * unit(f, P)["cm"] >= fixed_curve(f):
            return f
    return None


def solve_price(P, target_cm, f):
    lo, hi = 100, 4000
    for _ in range(60):
        mid = (lo + hi) / 2
        if unit(f, dict(P, list=mid))["cm"] < target_cm:
            lo = mid
        else:
            hi = mid
    return round(hi)


def tbl(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    for row in rows:
        out.append("| " + " | ".join(str(x) for x in row) + " |")
    print("\n".join(out))
    print()


def r(x, n=0):
    return f"{x:,.{n}f}"


