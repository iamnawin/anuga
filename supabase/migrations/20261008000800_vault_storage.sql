-- Vault files and consents (M8).
--
-- Files live in a private storage bucket that no app role can touch directly
-- (no storage.objects policies). The vault-files Edge Function issues short-lived
-- signed URLs with the service role, and only after these functions authorize
-- the caller with their own JWT:
--   upload:   vault_create_document  (owner/editor + the owner's active vault consent;
--             the storage path is generated here, never chosen by the client)
--   confirm:  vault_upload_target, then vault_mark_uploaded (service role)
--   download: vault_document_download (the audited vault read, same as vault_list_documents)
-- Vault writes (documents, vitals, medicines) now need the owner's active vault consent.

insert into public.app_settings (key, value, description) values
  ('vault_max_upload_bytes', '10485760', 'Largest vault file accepted (bytes)'),
  ('vault_allowed_content_types', '["image/jpeg", "image/png", "image/webp", "application/pdf"]',
   'File types accepted in the vault'),
  ('vault_signed_url_seconds', '60', 'Lifetime of a signed download URL');

alter table public.vault_documents
  add column status text not null default 'uploaded' check (status in ('pending_upload', 'uploaded')),
  add column content_type text,
  add column size_bytes integer check (size_bytes > 0);

-- Paths are generated by vault_create_document; a client must not choose one
-- (it could point a record at another patient's file).
revoke insert on public.vault_documents from authenticated;
drop policy editors_insert on public.vault_documents;

-- Private bucket. Created here when the storage schema exists (Supabase local and
-- hosted); the PGlite test harness has no storage schema and skips it.
do $$
begin
  if exists (select 1 from pg_namespace where nspname = 'storage') then
    insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
    values ('vault', 'vault', false, 10485760, array['image/jpeg', 'image/png', 'image/webp', 'application/pdf'])
    on conflict (id) do update set public = false, file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;
  end if;
end;
$$;

-- Helpers ----------------------------------------------------------------------

-- True while the patient's owner has an active consent for the purpose.
create function private.owner_consent_active(p_patient_id uuid, p_purpose public.consent_purpose)
returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.consents c
    join public.patient_access pa
      on pa.patient_id = c.patient_id and pa.user_id = c.user_id and pa.access_level = 'owner'
    where c.patient_id = p_patient_id and c.purpose = p_purpose and c.withdrawn_at is null
  )
$$;

create function private.assert_service_role()
returns void
language plpgsql stable security definer set search_path = ''
as $$
begin
  if coalesce(current_setting('role', true), 'none') <> 'service_role'
     and coalesce(auth.jwt() ->> 'role', '') <> 'service_role' then
    raise exception 'service role only' using errcode = '42501';
  end if;
end;
$$;

-- Vault writes need the owner's consent --------------------------------------------

drop policy editors_insert on public.vitals;
drop policy editors_insert on public.medicines;
create policy editors_insert_with_consent on public.vitals for insert to authenticated
  with check (private.can_edit_patient(patient_id) and private.owner_consent_active(patient_id, 'vault'));
create policy editors_insert_with_consent on public.medicines for insert to authenticated
  with check (private.can_edit_patient(patient_id) and private.owner_consent_active(patient_id, 'vault'));

-- Documents ----------------------------------------------------------------------

create function public.vault_create_document(
  p_patient_id uuid, p_doc_type text, p_title text, p_content_type text, p_size_bytes integer
)
returns table (document_id uuid, storage_path text)
language plpgsql volatile security definer set search_path = ''
as $$
declare
  v_ext text;
  v_id uuid := gen_random_uuid();
  v_path text;
begin
  if not private.can_edit_patient(p_patient_id) then
    raise exception 'not allowed' using errcode = '42501';
  end if;
  if not private.owner_consent_active(p_patient_id, 'vault') then
    raise exception 'vault consent required' using errcode = '42501',
      hint = 'the patient''s owner must give the vault consent first';
  end if;
  if coalesce(trim(p_title), '') = '' then
    raise exception 'title is required' using errcode = '22023';
  end if;
  if not exists (
    select 1 from jsonb_array_elements_text(
      (select value from public.app_settings where key = 'vault_allowed_content_types')) t
    where t = p_content_type
  ) then
    raise exception 'file type % is not accepted', p_content_type using errcode = '22023';
  end if;
  if p_size_bytes is null or p_size_bytes <= 0 or p_size_bytes > private.setting_int('vault_max_upload_bytes') then
    raise exception 'file size % is not accepted', p_size_bytes using errcode = '22023';
  end if;

  v_ext := case p_content_type
    when 'image/jpeg' then 'jpg' when 'image/png' then 'png' when 'image/webp' then 'webp' else 'pdf' end;
  v_path := p_patient_id::text || '/' || v_id::text || '.' || v_ext;

  insert into public.vault_documents (id, patient_id, doc_type, title, storage_path, status, content_type, size_bytes, uploaded_by)
  values (v_id, p_patient_id, p_doc_type, trim(p_title), v_path, 'pending_upload', p_content_type, p_size_bytes, auth.uid());

  return query select v_id, v_path;
end;
$$;

-- Path of a document still waiting for its file, for an editor of the patient.
create function public.vault_upload_target(p_document_id uuid)
returns text
language plpgsql stable security definer set search_path = ''
as $$
declare
  v_doc public.vault_documents;
begin
  select * into v_doc from public.vault_documents where id = p_document_id;
  if not found or not private.can_edit_patient(v_doc.patient_id) then
    raise exception 'not allowed' using errcode = '42501';
  end if;
  if v_doc.status <> 'pending_upload' then
    raise exception 'document is already uploaded' using errcode = '22023';
  end if;
  return v_doc.storage_path;
end;
$$;

-- Called by the Edge Function (service role) once the file exists in storage.
create function public.vault_mark_uploaded(p_document_id uuid, p_size_bytes integer)
returns void
language plpgsql volatile security definer set search_path = ''
as $$
begin
  perform private.assert_service_role();
  update public.vault_documents set status = 'uploaded', size_bytes = p_size_bytes
  where id = p_document_id and status = 'pending_upload';
  if not found then
    raise exception 'document % is not waiting for upload', p_document_id using errcode = '22023';
  end if;
end;
$$;

-- Authorizes and audits a file read (same rule and audit row as vault_list_documents),
-- then returns where the file is and how long a signed URL may live (app_settings).
-- Unknown documents look the same as forbidden ones.
create function public.vault_document_download(p_document_id uuid, p_purpose text default null)
returns table (storage_path text, content_type text, url_seconds integer)
language plpgsql volatile security definer set search_path = ''
as $$
declare
  v_doc public.vault_documents;
begin
  select * into v_doc from public.vault_documents where id = p_document_id;
  if not found then
    raise exception 'not allowed' using errcode = '42501';
  end if;
  perform private.authorize_vault_read(v_doc.patient_id, 'vault_documents', coalesce(p_purpose, 'file download'));
  if v_doc.status <> 'uploaded' then
    raise exception 'document file is not uploaded yet' using errcode = '22023';
  end if;
  return query select v_doc.storage_path, v_doc.content_type, private.setting_int('vault_signed_url_seconds');
end;
$$;

-- Consents -----------------------------------------------------------------------

-- Each purpose for a patient: whether the owner's consent is active, and whether
-- the caller may change it (owner only).
create function public.family_consents(p_patient_id uuid)
returns table (purpose public.consent_purpose, active boolean, granted_at timestamptz, can_change boolean)
language plpgsql stable security definer set search_path = ''
as $$
begin
  if not private.can_view_patient(p_patient_id) then
    raise exception 'not allowed' using errcode = '42501';
  end if;
  return query
  select p.purpose,
         private.owner_consent_active(p_patient_id, p.purpose),
         (select max(c.granted_at) from public.consents c
          join public.patient_access pa on pa.patient_id = c.patient_id and pa.user_id = c.user_id and pa.access_level = 'owner'
          where c.patient_id = p_patient_id and c.purpose = p.purpose and c.withdrawn_at is null),
         private.access_level_for(p_patient_id) = 'owner'
  from unnest(enum_range(null::public.consent_purpose)) p(purpose)
  order by p.purpose;
end;
$$;

-- Owner gives (p_active = true) or withdraws (false) a consent. Idempotent; each
-- change is a consents row change, audited by its trigger.
create function public.set_consent(p_patient_id uuid, p_purpose public.consent_purpose, p_active boolean)
returns boolean
language plpgsql volatile security definer set search_path = ''
as $$
begin
  if private.access_level_for(p_patient_id) is distinct from 'owner' then
    raise exception 'only the owner can change consents' using errcode = '42501';
  end if;
  if p_active then
    if not private.owner_consent_active(p_patient_id, p_purpose) then
      insert into public.consents (user_id, patient_id, purpose) values (auth.uid(), p_patient_id, p_purpose);
    end if;
  else
    update public.consents set withdrawn_at = now()
    where patient_id = p_patient_id and user_id = auth.uid() and purpose = p_purpose and withdrawn_at is null;
  end if;
  return private.owner_consent_active(p_patient_id, p_purpose);
end;
$$;

revoke execute on function private.owner_consent_active(uuid, public.consent_purpose), private.assert_service_role()
from public, anon, authenticated;
